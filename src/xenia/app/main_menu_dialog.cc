MainMenuWindow::MainMenuWindow(ui::ImGuiDrawer* imgui_drawer,
                               EmulatorWindow* emulator_window)
    : ui::ImGuiDialog(imgui_drawer), emulator_window_(emulator_window) {
  std::function<void(uint8_t)> f = std::bind(
      &MainMenuWindow::OnGuideButtonPress, this, std::placeholders::_1);
  imgui_drawer->SetGuideButtonAction(f);

  currently_selected_submenu_ = std::make_unique<RecentlyPlayedContentDialog>(
      imgui_drawer, emulator_window);
}

MainMenuWindow::~MainMenuWindow() { XELOGE("WAIT"); }

void MainMenuWindow::OnGuideButtonPress(uint8_t controller_index) {
  controller_index_ = controller_index;
  is_visible_ ^= true;
}

