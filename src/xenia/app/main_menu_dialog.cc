void MainMenuWindow::OnDraw(ImGuiIO& io) {
  if (!is_visible_) {
    ImGui::SetNextWindowCollapsed(true, ImGuiCond_Always);
    // return;
  }

  if (!has_opened_) {
    ImGui::OpenPopup("Main Menu");
    has_opened_ = true;
  }

  ImGuiViewport* viewport = ImGui::GetMainViewport();
  ImGui::SetNextWindowPos(viewport->Pos);
  ImGui::SetNextWindowSize(viewport->Size);

  bool dialog_open = true;
  if (!ImGui::BeginPopupModal("Main Menu", &dialog_open,
                              ImGuiWindowFlags_NoDecoration)) {
    Close();
    return;
  }

  const float sidebar_size = ImGui::GetContentRegionAvail().x * 0.2f;
  const float content_size = ImGui::GetContentRegionAvail().x - sidebar_size;

  DrawSidebarMenu(sidebar_size);
  ImGui::SameLine();
  DrawContentView(content_size);

  ImGui::End();
}

void MainMenuWindow::DrawSidebarMenu(const float width) {
  const float button_height = 60.f;

  ImGui::BeginChild(
      "MainMenuSidebar", ImVec2(width, 0),
      ImGuiChildFlags_NavFlattened | ImGuiChildFlags_AutoResizeX,
      ImGuiWindowFlags_NoScrollbar | ImGuiWindowFlags_NoScrollWithMouse);

  DrawXeniaInfo();
  ImGui::Separator();

  if (!was_cursor_set_) {
    ImGui::SetKeyboardFocusHere();
    // ImGui::SetItemDefaultFocus();
    was_cursor_set_ = true;
  }

  ImGui::Dummy(ImVec2(10.f, 10.f));

  ImGui::PushFont(emulator_window_->imgui_drawer()->GetTitleFont());

  if (ImGui::Button("Open Recent", ImVec2(width * 0.90f, button_height))) {
    current_content_ = MainMenuUiContent::recent;
    currently_selected_submenu_ = std::make_unique<RecentlyPlayedContentDialog>(
        imgui_drawer(), emulator_window_);
  }

  if (ImGui::Button("Open", ImVec2(width * 0.90f, button_height))) {
    currently_selected_submenu_.reset();
  }

  if (ImGui::Button("Install", ImVec2(width * 0.90f, button_height))) {
    currently_selected_submenu_.reset();
  }

  if (ImGui::Button("Profiles", ImVec2(width * 0.90f, button_height))) {
    current_content_ = MainMenuUiContent::profiles;
    currently_selected_submenu_.reset();
  }

  if (ImGui::Button("Settings", ImVec2(width * 0.90f, button_height))) {
    current_content_ = MainMenuUiContent::settings;
    currently_selected_submenu_.reset();
  }

  if (ImGui::Button("About", ImVec2(width * 0.90f, button_height))) {
    current_content_ = MainMenuUiContent::about;
    currently_selected_submenu_.reset();
  }

  ImGui::PopFont();
  ImGui::Separator();

  ImGui::Dummy(ImVec2(150.f, 150.f));

  DrawCurrentlySignedProfile();

  ImGui::EndChild();
}

void MainMenuWindow::DrawContentView(const float width) {
  ImGui::BeginChild("MainMenuContent", ImVec2(width, 0), true);

  if (currently_selected_submenu_) {
    currently_selected_submenu_->Draw();
  }

  switch (current_content_) {
    case MainMenuUiContent::recent:
      // DrawRecentMenu();
      break;
    case MainMenuUiContent::profiles:
      DrawProfilesMenu();
      break;
    case MainMenuUiContent::settings:
      DrawSettings();
      break;
    case MainMenuUiContent::about:
      DrawAbout();
      break;
    default:
      // DrawRecentMenu();
      break;
  }

  ImGui::EndChild();
}

void MainMenuWindow::DrawCurrentlySignedProfile() {
  if (emulator_window_ && emulator_window_->emulator()->kernel_state()) {
    const auto profile = emulator_window_->emulator()
                             ->kernel_state()
                             ->xam_state()
                             ->profile_manager()
                             ->GetProfile(controller_index_);

    if (profile) {
      const auto icon = emulator_window_->imgui_drawer()->GetNotificationIcon(
          controller_index_);

      if (icon && controller_index_ < XUserMaxUserCount) {
        ImGui::Image(reinterpret_cast<ImTextureID>(icon),
                     ui::default_image_icon_size);
      } else {
        ImGui::Dummy(ui::default_image_icon_size);
      }

      ImGui::SameLine();

      ImGui::BeginGroup();
      ImGui::Text("%s", profile->name().c_str());
      ImGui::Text("Profile XUID: %s",
                  fmt::format("{:016X}", profile->xuid()).c_str());
      ImGui::Text("Signed into slot: %i", controller_index_ + 1);
      ImGui::EndGroup();
    }
  } else {
    ImGui::Button("Sign-in");
  }
}

