test_mcrxr_1:
  #_ REGISTER_IN r3 0x0000000000000001
  #_ REGISTER_IN r4 0x0000000000000001
  addc r5, r3, r4
  mcrxr 1
  blr
  #_ REGISTER_OUT r3 0x0000000000000001
  #_ REGISTER_OUT r4 0x0000000000000001
  #_ REGISTER_OUT r5 0x0000000000000002
  #_ REGISTER_OUT cr 0x00000000
  #_ REGISTER_OUT xer 0x00000000

test_mcrxr_2:
  #_ REGISTER_IN r3 0xFFFFFFFFFFFFFFFF
  #_ REGISTER_IN r4 0x0000000000000001
  addc r5, r3, r4
  mcrxr 2
  blr
  #_ REGISTER_OUT r3 0xFFFFFFFFFFFFFFFF
  #_ REGISTER_OUT r4 0x0000000000000001
  #_ REGISTER_OUT r5 0x0000000000000000
  #_ REGISTER_OUT cr 0x00200000
  #_ REGISTER_OUT xer 0x00000000

# XER[SO] and XER[OV] reach a CR field.
test_mcrxr_3:
  #_ REGISTER_IN r3 0x7FFFFFFFFFFFFFFF
  #_ REGISTER_IN r4 0x0000000000000001
  addo r5, r3, r4
  mcrxr 0
  blr
  #_ REGISTER_OUT r5 0x8000000000000000
  #_ REGISTER_OUT cr 0xC0000000
  #_ REGISTER_OUT xer 0x00000000
