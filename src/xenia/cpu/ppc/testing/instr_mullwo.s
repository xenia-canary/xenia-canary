# The product no longer fits back into a word.
test_mullwo_2:
  #_ REGISTER_IN r4 0x0000000000010000
  #_ REGISTER_IN r5 0x0000000000010000
  mullwo r3, r4, r5
  blr
  #_ REGISTER_OUT r3 0x0000000100000000
  #_ REGISTER_OUT xer 0xC0000000

