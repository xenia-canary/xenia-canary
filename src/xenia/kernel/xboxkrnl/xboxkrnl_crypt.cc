dword_result_t XeKeysConsolePrivateKeySign_entry(
    lpvoid_t hash, pointer_t<XE_CONSOLE_CERTIFICATE> output) {
  if (!hash) {
    return false;
  }

  if (!output || !key_vault_retail.contains(0x36)) {
    return false;
  }

  std::span<const uint8_t> key_needed = key_vault_retail.at(0x36);
  auto& key_info = X_Key_Properties.at(0x36);
  uint32_t key_length = std::get<1>(key_info);
  std::memcpy(output, key_needed.data(), key_length);

  return true;
}
